/**
 * Personal API tokens for the MCP endpoint, for clients that send an
 * `Authorization` header (Claude Code, Cursor, the manual JSON config).
 * Only a SHA-256 hash is stored; the token is shown once. See `src/lib/mcp/tokens.ts`.
 */
export const apiTokens = pgTable("api_tokens", {
  id: text("id").primaryKey().$defaultFn(() => crypto.randomUUID()),
  userId: text("user_id").notNull().references(() => authUser.id, { onDelete: "cascade" }),
  name: text("name").notNull(),
  prefix: text("prefix").notNull(),
  tokenHash: text("token_hash").notNull().unique(),
  /** The token sealed with `secret-box`, so it can be revealed again. Null for tokens from before reveal existed. */
  tokenEncrypted: text("token_encrypted"),
  /** The one token every user gets automatically, used in the setup guides. */
  isDefault: boolean("is_default").notNull().default(false),
  readOnly: boolean("read_only").notNull().default(false),
  expiresAt: timestamp("expires_at", { withTimezone: true }),
  lastUsedAt: timestamp("last_used_at", { withTimezone: true }),
  revokedAt: timestamp("revoked_at", { withTimezone: true }),
  createdAt: timestamps.createdAt,
}, (table) => [index("api_tokens_user_idx").on(table.userId)]);

